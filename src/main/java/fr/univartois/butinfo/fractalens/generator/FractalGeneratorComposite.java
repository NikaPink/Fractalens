package fr.univartois.butinfo.fractalens.generator;
import fr.univartois.butinfo.fractalens.image.IFractalImage;

import java.awt.Color;
import java.util.ArrayList;
import java.util.List;
import com.madgag.gif.fmsware.AnimatedGifEncoder;

/**
 * The FractalGeneratorComposite class implements the Composite design pattern
 * to manage and execute multiple fractal generators. It collects the generated
 * images to produce an animated GIF file.
 *
 * @author TonNom
 *
 * @version 0.1.0
 */
public class FractalGeneratorComposite implements IFractalGenerator {

    /**
     * The delay in milliseconds between each frame of the animated GIF.
     */
    private int delay;

    /**
     * The file path where the animated GIF will be saved.
     */
    private String outputPath;

    /**
     * The collection of images generated by the child generators.
     */
    private List<IFractalImage> images;

    /**
     * The collection of child fractal generators to execute.
     */
    private List<IFractalGenerator> generators;

    /**
     * Constructs a new FractalGeneratorComposite.
     *
     * @param delay The delay in milliseconds between frames in the animation.
     * @param outputPath The output path where the GIF file will be saved.
     */
    public FractalGeneratorComposite(int delay, String outputPath) {
        this.delay = delay;
        this.outputPath = outputPath;
        images = new ArrayList<>();
        generators = new ArrayList<>();
    }

    /**
     * Adds a new fractal generator to the composite.
     *
     * @param generator The fractal generator to add.
     */
    public void addGenerator(IFractalGenerator generator) {
        generators.add(generator);
    }

    /**
     * Generates a fractal image by delegating the generation process to all
     * registered child generators. The resulting images are stored internally.
     *
     * @return The last generated image from the collection.
     */
    @Override
    public IFractalImage generateImage() {
        for(IFractalGenerator generator : generators) {
            images.add(generator.generateImage());
        }
        return images.getLast();
    }

    /**
     * Computes the color of a specific pixel.
     * This operation is not supported by the composite, as pixel computation
     * is the responsibility of individual generators.
     *
     * @param row The row of the pixel.
     * @param column The column of the pixel.
     *
     * @return Never returns normally.
     *
     * @throws UnsupportedOperationException Always thrown because a composite does not compute individual pixels.
     */
    @Override
    public Color computePixelColor(int row, int column) {
        throw new UnsupportedOperationException("This operation is not supported by the composite");
    }

    /**
     * Saves all generated images as a single animated GIF file to the specified output path.
     * This method utilizes the AnimatedGifEncoder to assemble the frames.
     */
    @Override
    public void saveImage() {
        AnimatedGifEncoder encoder = new AnimatedGifEncoder();
        encoder.start(outputPath);
        encoder.setDelay(delay);
        encoder.setRepeat(0);
        encoder.setQuality(10);
        for (IFractalImage image : images) {
            encoder.addFrame(image.asBufferedImage());
        }
        encoder.finish();
    }

    /**
     * Retrieves the list of child generators managed by this composite.
     *
     * @return The list of fractal generators.
     */
    public List<IFractalGenerator> getGenerators() {
        return generators;
    }
}
