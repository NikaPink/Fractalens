package fr.univartois.butinfo.fractalens.generator;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import fr.univartois.butinfo.fractalens.image.BufferedImageAdapter;
import fr.univartois.butinfo.fractalens.image.IFractalImage;
import java.awt.Color;
import java.io.File;
import java.nio.file.Path;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * The FractalGeneratorCompositeTest tests the Composite pattern implementation
 * for delegating fractal generation tasks.
 *
 * @author FractaLens Team
 */
class FractalGeneratorCompositeTest {

    private FractalGeneratorComposite composite;
    private FractalGeneratorSpy child1;
    private FractalGeneratorSpy child2;

    @BeforeEach
    void setUp() {
        composite = new FractalGeneratorComposite(100, "test_animation.gif");
        child1 = new FractalGeneratorSpy();
        child2 = new FractalGeneratorSpy();
    }

    /**
     * Tests that a newly created composite has an empty generator list.
     */
    @Test
    void testInitialState() {
        FractalGeneratorComposite newComposite = new FractalGeneratorComposite(50, "out.gif");
        assertNotNull(newComposite.getGenerators());
        assertTrue(newComposite.getGenerators().isEmpty());
    }

    /**
     * Tests adding child generators to the composite.
     */
    @Test
    void testAddGenerator() {
        composite.addGenerator(child1);
        composite.addGenerator(child2);

        assertEquals(2, composite.getGenerators().size());
    }

    /**
     * Tests that generateImage delegates to all registered child generators.
     */
    @Test
    void testGenerateImageDelegatesToAllChildren() {
        composite.addGenerator(child1);
        composite.addGenerator(child2);

        composite.generateImage();

        assertTrue(child1.isGenerateImageCalled());
        assertTrue(child2.isGenerateImageCalled());
    }

    /**
     * Tests that generateImage returns the image generated by the last child generator.
     */
    @Test
    void testGenerateImageReturnsLastImage() {
        IFractalImage image1 = new BufferedImageAdapter(10, 10);
        IFractalImage image2 = new BufferedImageAdapter(20, 20);

        child1.setImageToReturn(image1);
        child2.setImageToReturn(image2);

        composite.addGenerator(child1);
        composite.addGenerator(child2);

        IFractalImage result = composite.generateImage();
        assertEquals(image2, result);
    }

    /**
     * Tests that computePixelColor throws UnsupportedOperationException.
     */
    @Test
    void testComputePixelColorThrowsException() {
        UnsupportedOperationException exception = assertThrows(
                UnsupportedOperationException.class,
                () -> composite.computePixelColor(0, 0)
        );
        assertEquals("This operation is not supported by the composite", exception.getMessage());
    }

    /**
     * Tests saving the generated images as an animated GIF file.
     *
     * @param tempDir Temporary directory provided by JUnit.
     */
    @Test
    void testSaveImage(@TempDir Path tempDir) {
        File gifFile = tempDir.resolve("animation.gif").toFile();
        FractalGeneratorComposite gifComposite = new FractalGeneratorComposite(50, gifFile.getAbsolutePath());

        IFractalImage image1 = new BufferedImageAdapter(10, 10);
        IFractalImage image2 = new BufferedImageAdapter(10, 10);

        child1.setImageToReturn(image1);
        child2.setImageToReturn(image2);

        gifComposite.addGenerator(child1);
        gifComposite.addGenerator(child2);

        gifComposite.generateImage();
        gifComposite.saveImage();

        assertTrue(gifFile.exists());
        assertTrue(gifFile.length() > 0);
    }

    /**
     * A spy class to track method calls on IFractalGenerator without executing real logic.
     */
    private static class FractalGeneratorSpy implements IFractalGenerator {

        private boolean generateImageCalled = false;
        private boolean saveImageCalled = false;
        private boolean computePixelColorCalled = false;
        private IFractalImage imageToReturn = null;

        public void setImageToReturn(IFractalImage image) {
            this.imageToReturn = image;
        }

        @Override
        public IFractalImage generateImage() {
            this.generateImageCalled = true;
            return imageToReturn;
        }

        @Override
        public Color computePixelColor(int row, int column) {
            this.computePixelColorCalled = true;
            return Color.BLACK;
        }

        @Override
        public void saveImage() {
            this.saveImageCalled = true;
        }

        public boolean isGenerateImageCalled() {
            return generateImageCalled;
        }

        public boolean isSaveImageCalled() {
            return saveImageCalled;
        }

        public boolean isComputePixelColorCalled() {
            return computePixelColorCalled;
        }
    }
}
